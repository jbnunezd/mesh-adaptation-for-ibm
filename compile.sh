#!/bin/bash
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# Exit if errors take place
#----------------------------------------------------------------------------------------------------------------------#
set -e
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# ROOT FOLDER
#----------------------------------------------------------------------------------------------------------------------#
export PROJECT_ROOT=$(dirname $(realpath "${BASH_SOURCE[0]}"))
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# PROJECT NAME
#----------------------------------------------------------------------------------------------------------------------#
export PROJECT_NAME="ARIEN-MESH-ADAPTATION-FOR-IBM"
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# FUNCTION: COLOR STRING
#----------------------------------------------------------------------------------------------------------------------#
function colour_string ()
{
  local STRING="$1"
  WC='\033[1;34m'
  NC='\033[0m'
  printf "${WC}${STRING}${NC}"
}
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# FUNCTION: HELP
#----------------------------------------------------------------------------------------------------------------------#
function help_main()
{
  echo "Usage: $0 [ -b | --build ] [ -d | --debug ] [ -r | --release ] [ -c | --clean ] [ -h | --help  ]"
  exit 2
}
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# FUNCTION: COPY FILES
#----------------------------------------------------------------------------------------------------------------------#
function copy_files()
{
  local SOURCE_FOLDER="$1"
  local TARGET_FOLDER="$2"
  for FILE in "${SOURCE_FOLDER}"/*
  do
    local MESSAGE="${FILE##*/}"
    printf "Installing ./bin/${MESSAGE}\n"
    cp "${FILE}" "${TARGET_FOLDER}"/. || exit
  done
}
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# FUNCTION: BANNER FOR PROMPTING PROCESS
#----------------------------------------------------------------------------------------------------------------------#
function banner()
{
  local MESSAGE="$1"
  printf "%`tput cols`s\n"|tr ' ' '='
  printf "${MESSAGE}\n"
  printf "%`tput cols`s\n"|tr ' ' '='
}
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# FUNCTION: BUILD
#----------------------------------------------------------------------------------------------------------------------#
function build_main()
{
  local OPT_BUILD_TYPE="${BUILD_TYPE}"
  local MESSAGE="BUILDING ${PROJECT_NAME} :: ${OPT_BUILD_TYPE}"
  banner "${MESSAGE}"
  if [ ! -d "${PROJECT_ROOT}/build" ]; then
    mkdir "${PROJECT_ROOT}/build" || exit
  fi
  cd "${PROJECT_ROOT}/build" || exit
  cd "${PROJECT_ROOT}/build" || exit
  cmake -DCMAKE_BUILD_TYPE="${OPT_BUILD_TYPE}" "${PROJECT_ROOT}" || exit
  cmake -DCMAKE_BUILD_TYPE="${OPT_BUILD_TYPE}" "${PROJECT_ROOT}" || exit
  make || exit
  SOURCE="${PROJECT_ROOT}/build/bin"
  TARGET="${PROJECT_ROOT}/bin"
  local MESSAGE="INSTALLING EXECUTABLES"
  banner "${MESSAGE}"
  copy_files "${SOURCE}" "${TARGET}"
  cd "${PROJECT_ROOT}" || exit
}
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# FUNCTION: CLEAN
#----------------------------------------------------------------------------------------------------------------------#
function clean_main()
{
  local MESSAGE="CLEANING ${PROJECT_NAME}"
  banner "${MESSAGE}"
  if [ ! -d "${PROJECT_ROOT}/build" ]; then
    exit
  fi
  printf "rm -rf ${PROJECT_ROOT}/bin/*\n"
  rm -rf ${PROJECT_ROOT}/bin/* || exit
  printf "rm -rf ${PROJECT_ROOT}/build/*\n"
  rm -rf ${PROJECT_ROOT}/build/* || exit
  cd "${PROJECT_ROOT}" || exit
}
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
# ARGUMENTS AND OPTIONS
#----------------------------------------------------------------------------------------------------------------------#
OPTS_SHORT=b:,d,r,c,h
OPTS_LONG=build:,debug,release,clean,help
OPTS=$(getopt --alternative --name "${PROJECT_NAME}" --options ${OPTS_SHORT} --longoptions ${OPTS_LONG} -- "$@")
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
VALID_ARGUMENTS=$#
if [ "${VALID_ARGUMENTS}" -eq 0 ]; then
  help_main
fi
eval set -- "${OPTS}"
#----------------------------------------------------------------------------------------------------------------------#
OPT_BUILD=false
OPT_CLEAN=false
OPT_HELP=false
while true; do
  case "$1" in
    -b | --build )
      BUILD_TYPE="$2"
      OPT_BUILD=true;
      shift 2 ;;
    -d | --debug )
      BUILD_TYPE="Debug"
      OPT_BUILD=true;
      shift ;;
    -r | --release )
      BUILD_TYPE="Release"
      OPT_BUILD=true;
      shift ;;
    -c | --clean )
      OPT_CLEAN=true;
      shift ;;
    -h | --help )
      OPT_HELP=true;
      shift ;;
    -- )
      shift;
      break ;;
    * )
      echo "Unexpected option: $1" ;;
  esac
done
#----------------------------------------------------------------------------------------------------------------------#
#
#----------------------------------------------------------------------------------------------------------------------#
if [ "${OPT_BUILD}" == "true" ]; then
  OPT_CLEAN=false
  OPT_HELP=false
  build_main
fi
#----------------------------------------------------------------------------------------------------------------------#
if [ "${OPT_CLEAN}" == "true" ]; then
  OPT_BUILD=false
  OPT_HELP=false
  clean_main
fi
#----------------------------------------------------------------------------------------------------------------------#
if [ "${OPT_HELP}" == "true" ]; then
  help_main
fi
#----------------------------------------------------------------------------------------------------------------------#
